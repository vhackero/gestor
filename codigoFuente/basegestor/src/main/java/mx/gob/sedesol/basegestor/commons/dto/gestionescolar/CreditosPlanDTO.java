public class CreditosPlanDTO {
	private Long idCreditosTotales;
	private Long idPlan;
	private Long totalCreditos;

	public Long getIdCreditosTotales() {
		return idCreditosTotales;
	}

	public void setIdCreditosTotales(Long idCreditosTotales) {
		this.idCreditosTotales = idCreditosTotales;
	}

	public Long getIdPlan() {
		return idPlan;
	}

	public void setIdPlan(Long idPlan) {
		this.idPlan = idPlan;
	}

	public Long getTotalCreditos() {
		return totalCreditos;
	}

	public void setTotalCreditos(Long totalCreditos) {
		this.totalCreditos = totalCreditos;
	}

}
